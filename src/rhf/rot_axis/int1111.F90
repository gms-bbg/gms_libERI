        ket_loop = 0
        do k = 1, res%contr_num(ksh)*res%contr_num(lsh)
          ket_loop = ket_loop + 1
          t_expon_cd = pp_pair%t_expon_ab(pp_pair%pair_loc(kl) + ket_loop) ! buff(3) = expon_cd_sp
